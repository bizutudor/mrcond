"""Full benchmark from recorded LLM outputs, plus the README results tables.

``run_full_benchmark`` evaluates, without any model:

* the rule extractor (with and without the verifier) on the whole Track S test split and on Track R;
* every recorded LLM in ``data/replay`` (``<tag>.jsonl`` = greedy run 0; ``<tag>.runN.jsonl`` = sampled runs used
  for run-to-run consistency) on Track R and on the Track S documents it was recorded on, next to the rule
  extractor on exactly the same documents.

``readme_results(results)`` renders the README tables from the JSON so that the README numbers always match
``reports/benchmark_results.json`` (a test regenerates and compares them).
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

from .. import __version__
from ..extractors.backends import ReplayBackend
from ..extractors.llm import PROMPT_VERSION, LLMExtractor
from ..extractors.rule import RuleExtractor
from .metrics import consistency
from .runner import evaluate, load_track_r, load_track_s

__all__ = ["run_full_benchmark", "readme_results", "report_markdown", "replay_tags"]

README_START = "<!-- results:start (generated by scripts/benchmark_report.py from reports/benchmark_results.json) -->"
README_END = "<!-- results:end -->"


def replay_tags(replay_dir: Path) -> list[str]:
    return sorted(p.stem for p in replay_dir.glob("*.jsonl") if ".run" not in p.stem)


def _recorded_ids(path: Path) -> list[str]:
    if not path.exists():
        return []
    return [json.loads(line)["doc_id"] for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def _entry(res, **extra) -> dict:
    return {**res.metrics, "seconds": res.seconds, **extra}


def run_full_benchmark(replay_dir: str | Path, setup: dict | None = None) -> dict:
    replay_dir = Path(replay_dir)
    track_s = load_track_s("test")
    track_r, missing = load_track_r()
    out: dict = {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "mrcond_version": __version__,
        "prompt_version": PROMPT_VERSION,
        "setup": setup or {},
        "tracks": {
            "S": {
                "description": "Track S (synthetic, exact ground truth), test split",
                "n_docs": len(track_s),
                "results": {},
            },
            "R": {
                "description": "Track R (real public labeling) - on DRAFT annotations pending human verification",
                "n_docs": len(track_r),
                "missing_text": missing,
                "results": {},
            },
        },
    }
    for track, items in (("S", track_s), ("R", track_r)):
        for name in ("rule", "rule+verifier"):
            out["tracks"][track]["results"][name] = _entry(
                evaluate(items, RuleExtractor(), name.endswith("verifier"), name), docs="all"
            )
    for tag in replay_tags(replay_dir):
        base = replay_dir / f"{tag}.jsonl"
        recorded = set(_recorded_ids(base))
        runs = [base] + sorted(replay_dir.glob(f"{tag}.run*.jsonl"))
        for track, items in (("S", track_s), ("R", track_r)):
            sub = [it for it in items if it[0].doc_id in recorded]
            if not sub:
                continue
            res_t = out["tracks"][track]["results"]
            if len(sub) < len(items):  # the rule extractor on exactly the LLM's documents, for a fair comparison
                ids = [d.doc_id for d, _, _ in sub]
                for name in ("rule", "rule+verifier"):
                    key = f"{name} (LLM subset, {len(sub)} docs)"
                    if key in res_t and res_t[key]["docs"] != ids:
                        key = f"{name} (subset of {tag}, {len(sub)} docs)"
                    if key not in res_t:
                        res_t[key] = _entry(evaluate(sub, RuleExtractor(), name.endswith("verifier"), name), docs=ids)
            for verify in (False, True):
                name = f"llm{'+verifier' if verify else ''}:{tag}"
                preds_by_run = []
                first = None
                for run, path in enumerate(runs):
                    run_no = 0 if path == base else int(path.stem.rsplit(".run", 1)[1])
                    ex = LLMExtractor(
                        ReplayBackend(path), tag, run=run_no, temperature=0.0 if run_no == 0 else 0.7, seed=run_no
                    )
                    run_items = sub if run_no == 0 else [it for it in sub if it[0].doc_id in set(_recorded_ids(path))]
                    if not run_items:
                        continue
                    r = evaluate(run_items, ex, verify, name)
                    preds_by_run.append(r.predictions)
                    if run == 0:
                        first = r
                assert first is not None
                entry = _entry(
                    first,
                    model=tag,
                    docs=[d.doc_id for d, _, _ in sub] if len(sub) < len(items) else "all",
                    skipped_no_recording=first.skipped,
                )
                if len(preds_by_run) > 1:
                    cons = []
                    for doc_id in preds_by_run[0]:
                        labels = [p[doc_id] for p in preds_by_run if doc_id in p]
                        c = consistency(labels)
                        if c is not None:
                            cons.append(c)
                    entry["run_to_run_consistency"] = round(sum(cons) / len(cons), 4) if cons else None
                    entry["consistency_runs"] = len(preds_by_run)
                    entry["consistency_docs"] = len(cons)
                res_t[name] = entry
    return out


def _pct(x: float | None) -> str:
    return "—" if x is None else f"{100 * x:.1f} %"


def _row(name: str, m: dict) -> str:
    cons = m.get("run_to_run_consistency")
    if cons is not None:
        cons_txt = f"{_pct(cons)} ({m['consistency_docs']} docs × {m['consistency_runs']} runs)"
    else:
        cons_txt = "deterministic" if name.startswith("rule") else "—"
    return (
        f"| {name} | {m['n_docs']} | {_pct(m['precision'])} | {_pct(m['recall'])} | {_pct(m['f1'])} | "
        f"{_pct(m['status_accuracy'])} | {m['unsupported_values']}/{m['n_values']} | "
        f"{m['less_conservative_errors']} ({_pct(m['less_conservative_rate'])}) | {_pct(m['abstention_rate'])} | "
        f"{_pct(m['selective_accuracy'])} | {cons_txt} |"
    )


_HEAD = (
    "| Extractor | Docs | Precision | Recall | F1 | MR status acc. | Unsupported values | "
    "Less-conservative errors (rate) | Abstention | Selective acc. | Run-to-run consistency |\n"
    "|---|---|---|---|---|---|---|---|---|---|---|"
)


def _display(name: str) -> str:
    return (
        name.replace("llm+verifier:", "LLM + verifier, ")
        .replace("llm:", "LLM, ")
        .replace("rule+verifier", "rule + verifier")
    )


def _lc_kinds(results: dict) -> list[str]:
    lines = []
    for name, m in results.items():
        if m["less_conservative_errors"]:
            kinds = ", ".join(f"{k} {v}" for k, v in sorted(m["less_conservative_by_kind"].items()))
            lines.append(f"* {_display(name)}: {kinds}")
    return lines


def readme_results(results: dict) -> str:
    """The README "Current results" block (tables only; prose around it lives in the README)."""
    lines = [README_START, ""]
    for track, title in (
        ("S", "Track S — synthetic test split"),
        ("R", "Track R — real labeling, draft annotations pending human verification"),
    ):
        t = results["tracks"][track]
        lines += [f"**{title}** ({t['n_docs']} documents)", "", _HEAD]
        for name, m in t["results"].items():
            lines.append(_row(_display(name), m))
        lines += ["", "Less-conservative errors by kind:", "", *_lc_kinds(t["results"]), ""]
    lines.append(README_END)
    return "\n".join(lines)


def report_markdown(results: dict) -> str:
    lines = [
        "# MRCond benchmark results",
        "",
        f"Generated: {results['generated_at']} (MRCond "
        f"{results['mrcond_version']}, prompt {results['prompt_version']})",
        "",
    ]
    if results.get("setup"):
        lines += ["## Setup", "", "```json", json.dumps(results["setup"], indent=1, ensure_ascii=False), "```", ""]
    for track, t in results["tracks"].items():
        lines += [f"## Track {track}", "", t["description"], "", f"Documents: {t['n_docs']}", ""]
        if t.get("missing_text"):
            lines += [f"Not fetched locally (skipped): {', '.join(t['missing_text'])}", ""]
        lines += [_HEAD]
        for name, m in t["results"].items():
            lines.append(_row(_display(name), m))
        lines += ["", "Less-conservative errors by kind:", "", *_lc_kinds(t["results"]), ""]
        groups: dict[tuple, list[str]] = {}
        for name, m in t["results"].items():
            if isinstance(m.get("docs"), list):
                groups.setdefault(tuple(m["docs"]), []).append(f"`{name}`")
        for ids, names in groups.items():
            lines.append(f"* Documents for {', '.join(names)}: {', '.join(ids)}")
        lines.append("")
    return "\n".join(lines) + "\n"
